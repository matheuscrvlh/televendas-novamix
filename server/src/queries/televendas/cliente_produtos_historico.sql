-- Produtos que o cliente mais compra, considerando todo o histórico com o time de televendas.
-- "VEZES" = em quantos pedidos diferentes o produto apareceu.
WITH ITENS AS (
    SELECT
        EA.IDPRODUTO,
        EA.IDSUBPRODUTO,
        EA.IDPLANILHA,
        EA.DTMOVIMENTO,
        EA.QTDPRODUTO,
        EA.VALTOTLIQUIDO
    FROM DBA.ESTOQUE_ANALITICO EA
    INNER JOIN DBA.NOTAS_ENTRADA_SAIDA NES
        ON NES.IDEMPRESA = EA.IDEMPRESA
        AND NES.IDPLANILHA = EA.IDPLANILHA
        AND NES.DTMOVIMENTO = EA.DTMOVIMENTO
    INNER JOIN DBA.NOTAS N
        ON N.IDEMPRESA = EA.IDEMPRESA
        AND N.IDPLANILHA = EA.IDPLANILHA
        AND N.FLAGNOTACANCEL = 'F'
    INNER JOIN DBA.OPERACAO_INTERNA OI
        ON OI.IDOPERACAO = EA.IDOPERACAO
        AND OI.FLAGMOVPRODUTOS = 'T'
        AND OI.TIPOMOVIMENTO = 'V'
    WHERE
        EA.IDVENDEDOR IN ({{VENDEDORES}})
        AND EA.IDOPERACAO <> 1301
        AND NES.TIPOITEMCATEGORIA NOT IN ('D8')
        AND COALESCE(EA.NUMSEQUENCIAKIT,0) <= 0
        AND N.IDCLIFOR = ?
)
SELECT
    I.IDSUBPRODUTO,
    P.DESCRCOMPRODUTO AS PRODUTO,
    COUNT(DISTINCT I.IDPLANILHA) AS VEZES,
    CAST(SUM(I.QTDPRODUTO) AS NUMERIC(15,3)) AS QUANTIDADE,
    CAST(SUM(I.VALTOTLIQUIDO) AS NUMERIC(15,2)) AS TOTAL,
    MAX(I.DTMOVIMENTO) AS ULTIMA_COMPRA
FROM ITENS I
INNER JOIN DBA.PRODUTO P
    ON P.IDPRODUTO = I.IDPRODUTO
GROUP BY I.IDSUBPRODUTO, P.DESCRCOMPRODUTO
ORDER BY VEZES DESC, TOTAL DESC;
