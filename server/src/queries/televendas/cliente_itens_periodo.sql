-- Itens que um cliente comprou no período, um registro por produto em cada pedido.
-- Só vendas (devoluções não entram) e sem os componentes de kit (NUMSEQUENCIAKIT > 0),
-- igual à regra de faturamento dos outros relatórios.
SELECT
    EA.IDEMPRESA,
    EA.IDPLANILHA,
    EA.DTMOVIMENTO,
    EA.IDSUBPRODUTO,
    P.DESCRCOMPRODUTO AS PRODUTO,
    CAST(SUM(EA.QTDPRODUTO) AS NUMERIC(15,3)) AS QUANTIDADE,
    CAST(SUM(EA.VALTOTLIQUIDO) AS NUMERIC(15,2)) AS TOTAL
FROM DBA.ESTOQUE_ANALITICO EA
INNER JOIN DBA.NOTAS_ENTRADA_SAIDA NES
    ON NES.IDEMPRESA = EA.IDEMPRESA
    AND NES.IDPLANILHA = EA.IDPLANILHA
    AND NES.DTMOVIMENTO = EA.DTMOVIMENTO
INNER JOIN DBA.NOTAS N
    ON N.IDEMPRESA = EA.IDEMPRESA
    AND N.IDPLANILHA = EA.IDPLANILHA
    AND N.FLAGNOTACANCEL = 'F'
INNER JOIN DBA.OPERACAO_INTERNA OI
    ON OI.IDOPERACAO = EA.IDOPERACAO
    AND OI.FLAGMOVPRODUTOS = 'T'
    AND OI.TIPOMOVIMENTO = 'V'
INNER JOIN DBA.PRODUTO P
    ON P.IDPRODUTO = EA.IDPRODUTO
WHERE
    EA.IDVENDEDOR IN ({{VENDEDORES}})
    AND EA.IDOPERACAO <> 1301
    AND NES.TIPOITEMCATEGORIA NOT IN ('D8')
    AND COALESCE(EA.NUMSEQUENCIAKIT,0) <= 0
    AND N.IDCLIFOR = ?
    AND EA.DTMOVIMENTO BETWEEN ? AND ?
GROUP BY EA.IDEMPRESA, EA.IDPLANILHA, EA.DTMOVIMENTO, EA.IDSUBPRODUTO, P.DESCRCOMPRODUTO
ORDER BY EA.DTMOVIMENTO DESC, EA.IDPLANILHA DESC, TOTAL DESC;
